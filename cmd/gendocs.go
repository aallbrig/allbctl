package cmd

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// cobra's own doc.GenMarkdownCustom appends this footer with time.Now(),
// with no option to disable it — strip it back out post-generation so the
// output stays deterministic (see the prepender comment below for why that
// matters for `docs-check`).
var cobraFooterRe = regexp.MustCompile(`\n\n###### Auto generated by spf13/cobra on [^\n]*\n$`)

var genDocsOutputDir string

var genDocsCmd = &cobra.Command{
	Use:    "gen-docs",
	Short:  "Generate markdown CLI reference documentation",
	Long:   `Generate markdown CLI reference documentation into the Hugo site's reference directory.`,
	Hidden: true,
	RunE: func(cmd *cobra.Command, args []string) error {
		if err := os.MkdirAll(genDocsOutputDir, 0755); err != nil {
			return fmt.Errorf("create output dir: %w", err)
		}

		// Write a _index.md with Hugo front matter for the reference section
		index := filepath.Join(genDocsOutputDir, "_index.md")
		indexContent := `---
weight: 99
bookFlatSection: true
title: "CLI Reference"
---

# CLI Reference

Auto-generated reference documentation for all allbctl commands and flags.

> This section is generated from the source code via ` + "`make gen-docs`" + `.
> Do not edit these files manually.
`
		if err := os.WriteFile(index, []byte(indexContent), 0644); err != nil {
			return fmt.Errorf("write _index.md: %w", err)
		}

		// Generate one markdown file per command with Hugo front matter prepended.
		// No date field: it isn't rendered anywhere for this section, and
		// stamping wall-clock time here made `docs-check` fail on any CI run
		// that lands on a later calendar day than the last commit.
		prepender := func(filename string) string {
			name := filepath.Base(filename)
			name = strings.TrimSuffix(name, ".md")
			return fmt.Sprintf("---\ntitle: \"%s\"\ndescription: \"auto-generated reference\"\n---\n\n", name)
		}
		linkHandler := func(name string) string { return name }

		if err := doc.GenMarkdownTreeCustom(rootCmd, genDocsOutputDir, prepender, linkHandler); err != nil {
			return fmt.Errorf("generate docs: %w", err)
		}

		entries, err := os.ReadDir(genDocsOutputDir)
		if err != nil {
			return fmt.Errorf("read output dir: %w", err)
		}
		for _, entry := range entries {
			if entry.IsDir() || entry.Name() == "_index.md" {
				continue
			}
			path := filepath.Join(genDocsOutputDir, entry.Name())
			content, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("read %s: %w", path, err)
			}
			stripped := cobraFooterRe.ReplaceAll(content, []byte("\n"))
			if !bytes.Equal(stripped, content) {
				if err := os.WriteFile(path, stripped, 0644); err != nil {
					return fmt.Errorf("write %s: %w", path, err)
				}
			}
		}

		fmt.Fprintf(os.Stderr, "docs written to %s\n", genDocsOutputDir)
		return nil
	},
}

func init() {
	genDocsCmd.Flags().StringVar(&genDocsOutputDir, "output", "hugo/site/content/docs/reference", "Directory to write generated docs")
	rootCmd.AddCommand(genDocsCmd)
}
